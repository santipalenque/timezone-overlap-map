// Generates src/geo.ts: the land outline as one SVG path and a coordinate per timezone.
// Run with `yarn geo` after updating world-atlas or the system tzdata; the output is committed.
//
// Land: Natural Earth 1:110m (public domain) via world-atlas.
// Zones: zone.tab (one location per zone) and links from tzdata.zi, so the CLDR names
// that Intl returns (Asia/Calcutta, America/Buenos_Aires) resolve too.

import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { feature } from 'topojson-client';

const require = createRequire(import.meta.url);
const ZONEINFO = process.env.ZONEINFO ?? '/usr/share/zoneinfo';

// Visible latitudes: Antarctica and the far Arctic only waste space on a working-hours map.
const NORTH = 84;
const SOUTH = -58;


// ---- land ----

const topo = require('world-atlas/land-110m.json');
const land = feature(topo, topo.objects.land);
const polygons = land.features.flatMap((f) =>
  f.geometry.type === 'MultiPolygon' ? f.geometry.coordinates : [f.geometry.coordinates],
);

// Land is drawn at 0.5-unit precision (about 1px at typical sizes) with relative moves,
// which keeps the path small; deltas come from quantized absolute points, so nothing drifts.
const STEP = 0.5;
const q = (n) => Math.round(n / STEP) * STEP;
const num = (n) => String(n).replace(/^(-?)0\./, '$1.');
const pair = (a, b) => {
  const second = num(b);
  return `${num(a)}${second.startsWith('-') ? '' : ' '}${second}`;
};

function ringPath(ring, shiftLon = 0) {
  const points = [];
  for (const [lon, lat] of ring) {
    const point = [q(lon + shiftLon + 180), q(NORTH - lat)];
    const prev = points[points.length - 1];
    if (!prev || prev[0] !== point[0] || prev[1] !== point[1]) points.push(point);
  }
  if (points.length < 3) return '';
  let d = `M${pair(...points[0])}l`;
  for (let i = 1; i < points.length; i++) {
    const dx = points[i][0] - points[i - 1][0];
    const dy = points[i][1] - points[i - 1][1];
    const part = pair(dx, dy);
    d += i > 1 && !part.startsWith('-') ? ` ${part}` : part;
  }
  return `${d}z`;
}

// longitudes made continuous across ±180, so a ring that wraps doesn't streak across the map
function unwrap(ring) {
  const out = [];
  let offset = 0;
  for (let i = 0; i < ring.length; i++) {
    const [lon, lat] = ring[i];
    if (i > 0) {
      const prev = ring[i - 1][0];
      if (lon - prev > 180) offset -= 360;
      else if (prev - lon > 180) offset += 360;
    }
    out.push([lon + offset, lat]);
  }
  return out;
}

let landPath = '';
let wrapped = 0;
for (const polygon of polygons) {
  for (const raw of polygon) {
    if (Math.max(...raw.map(([, lat]) => lat)) < SOUTH) continue; // Antarctica
    const ring = unwrap(raw);
    landPath += ringPath(ring);
    const lons = ring.map(([lon]) => lon);
    // a ring past the edge also shows up on the other side
    if (Math.max(...lons) > 180) (landPath += ringPath(ring, -360)), wrapped++;
    if (Math.min(...lons) < -180) (landPath += ringPath(ring, 360)), wrapped++;
  }
}

// ---- zones ----

// ±DDMM±DDDMM or ±DDMMSS±DDDMMSS
function parseCoord(text) {
  const m = /^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$/.exec(text);
  if (!m) throw new Error(`bad coordinate ${text}`);
  const deg = (sign, d, mm, ss = '0') => (sign === '-' ? -1 : 1) * (+d + +mm / 60 + +ss / 3600);
  // whole degrees: plenty for a dot on a small map
  return [Math.round(deg(m[1], m[2], m[3], m[4])), Math.round(deg(m[5], m[6], m[7], m[8]))];
}

const coords = {};
for (const line of readFileSync(`${ZONEINFO}/zone.tab`, 'utf8').split('\n')) {
  if (!line || line.startsWith('#')) continue;
  const [, coord, zone] = line.split('\t');
  coords[zone] = parseCoord(coord);
}

const zi = readFileSync(`${ZONEINFO}/tzdata.zi`, 'utf8');
const version = /^# version (\S+)/m.exec(zi)?.[1] ?? 'unknown';
let links = 0;
for (const line of zi.split('\n')) {
  const [kind, target, alias] = line.split(' ');
  if (kind === 'L' && coords[target] && !coords[alias]) {
    coords[alias] = coords[target];
    links++;
  }
}

const sorted = Object.fromEntries(Object.entries(coords).sort(([a], [b]) => a.localeCompare(b)));

writeFileSync(
  'src/geo.ts',
  `// Generated by scripts/build-geo.mjs — do not edit.
// Land: Natural Earth 1:110m (public domain) via world-atlas. Zones: IANA tzdata ${version}.

/** Equirectangular map: x = longitude + 180, y = ${NORTH} - latitude. */
export const MAP_NORTH = ${NORTH};
export const MAP_WIDTH = 360;
export const MAP_HEIGHT = ${NORTH - SOUTH};

export const LAND_PATH =
  ${JSON.stringify(landPath)};

/** [latitude, longitude] of each zone's main location. */
export const ZONE_COORDS: Record<string, readonly [number, number]> = ${JSON.stringify(sorted)};
`,
);

console.log(
  `src/geo.ts: land ${(landPath.length / 1024).toFixed(1)} KiB (${wrapped} wrapped copies), ` +
    `${Object.keys(coords).length} zones (${links} links), tzdata ${version}`,
);
